//! `cache-eviction-at-scale` R13.3 and R13.6: the acceptance bar shown on the eviction
//! mechanism itself rather than argued.
//!
//! | Module | Requirement | What it pins |
//! |---|---|---|
//! | `r13_3_extremes` | R13.3 over R1.3/R1.4 | A read-tier pass driven by `enforce_disk_cache_limits` reaches its byte target on the uniform-size extreme (tail empty by construction) and on the single-dominant-range extreme |
//! | `r13_6_cross_instance` | R13.6 | Selection follows a Tail_Partition another instance wrote, on a manager whose own state holds nothing about the key |
//!
//! Both extremes are generated by `tests/common/graded_fixture.rs`'s named distributions
//! (`SizeDistribution::Uniform`, `SizeDistribution::SingleDominant`), which until now only the
//! generator's own test exercised.

mod common;

use common::graded_fixture::{self, FixtureSpec, GeneratedFixture, PayloadMode, SizeDistribution};
use s3_proxy::cache::{CacheEvictionAlgorithm, CacheManager};
use s3_proxy::cache_size_tracker::TailRecord;
use s3_proxy::cache_types::{NewCacheMetadata, ObjectMetadata, RangeSpec};
use s3_proxy::compression::CompressionAlgorithm;
use s3_proxy::config::{MetadataCacheConfig, SharedStorageConfig};
use s3_proxy::disk_cache::get_sharded_path;
use std::path::{Path, PathBuf};
use std::time::{Duration, SystemTime, UNIX_EPOCH};
use tempfile::TempDir;

const TRIGGER_PERCENT: u8 = 95;
const TARGET_PERCENT: u8 = 80;

/// A manager with a real `max_cache_size_limit` and the journal components wired, so
/// `enforce_disk_cache_limits` reads its current size from Size_State.
fn manager(cache_dir: &Path, max_cache_size: u64) -> CacheManager {
    for sub in ["metadata/_journals", "size_tracking", "locks", "ranges"] {
        std::fs::create_dir_all(cache_dir.join(sub)).unwrap();
    }
    let m = CacheManager::new_with_shared_storage(
        cache_dir.to_path_buf(),
        false,
        0,
        max_cache_size,
        CacheEvictionAlgorithm::TinyLFU,
        1024,
        true,
        Duration::from_secs(315360000),
        Duration::from_secs(3600),
        Duration::from_secs(3600),
        false,
        SharedStorageConfig::default(),
        10.0,
        true,
        Duration::from_secs(86400),
        MetadataCacheConfig::default(),
        TRIGGER_PERCENT,
        TARGET_PERCENT,
        true,
        Duration::from_secs(60),
        1_048_576,
        false,
        Duration::from_secs(10),
        64,
        Duration::from_secs(5),
    );
    let _ = m.create_configured_disk_cache_manager();
    m
}

/// Install Size_State's total directly, as consolidation would leave it.
async fn seed_total(m: &CacheManager, total_size: u64) {
    let consolidator = m.get_journal_consolidator().await.expect("consolidator");
    let mut state = consolidator.load_size_state().await.unwrap();
    state.total_size = total_size;
    state.write_cache_size = 0;
    consolidator.persist_size_state(&state).await.unwrap();
}

/// The byte target the pass works to: `current - floor(max * target%)`, the figure
/// `perform_eviction_with_lock` computes as `bytes_to_free` (src/cache.rs).
fn bytes_to_free(current: u64, max: u64) -> u64 {
    current.saturating_sub((max as f64 * (TARGET_PERCENT as f64 / 100.0)) as u64)
}

/// R13.3: each of R1.3's extremes gets an eviction test.
///
/// The constrained line is the full-population arm of `perform_eviction_with_lock`
/// (`collect_range_candidates_for_eviction` → `sort_byte_dimension_candidates` →
/// `group_candidates_by_object(range_candidates, bytes_to_free)`). Neither fixture has a
/// Tail_Partition, because no rolling pass has run, so selection reports UNVISITED and this
/// arm is the mechanism under test. That is also the uniform extreme's production state:
/// with every size below `tail_floor_bytes` the partition is empty by construction.
mod r13_3_extremes {
    use super::*;

    fn generate(tmp: &Path, spec: &FixtureSpec) -> GeneratedFixture {
        let f = graded_fixture::generate(tmp, spec, true).expect("generation");
        for e in &f.emitted {
            assert!(
                tmp.join("ranges").join(&e.relative_bin_path).exists(),
                "fixture: every emitted .bin must exist before eviction: {}",
                e.relative_bin_path
            );
            assert_eq!(
                e.on_disk_size, e.recorded_compressed_size,
                "fixture: genuine payloads, so freed bytes and recorded bytes agree"
            );
        }
        f
    }

    /// Ranges whose `.bin` the pass removed, and their recorded bytes.
    fn evicted(tmp: &Path, f: &GeneratedFixture) -> (usize, u64) {
        f.emitted
            .iter()
            .filter(|e| !tmp.join("ranges").join(&e.relative_bin_path).exists())
            .fold((0, 0), |(n, b), e| (n + 1, b + e.recorded_compressed_size))
    }

    /// Uniform sizes: the tail is empty by construction, and R1.4 says byte-denominated
    /// selection reduces to entry-denominated selection. So the pass must reach the byte
    /// target, and it must do so with exactly `ceil(target / size)` ranges: one fewer misses
    /// the target, one more is an eviction the target did not ask for.
    #[tokio::test(flavor = "multi_thread")]
    async fn uniform_extreme_reaches_the_byte_target_with_the_entry_count_it_implies() {
        const SIZE: u64 = 8192;
        let tmp = TempDir::new().unwrap();
        let spec = FixtureSpec {
            label: "uniform".to_string(),
            bucket: "fixture-uniform".to_string(),
            objects: 300,
            max_ranges_per_object: 1,
            distribution: SizeDistribution::Uniform { size: SIZE },
            payload: PayloadMode::Genuine,
            ..FixtureSpec::default()
        };
        let f = generate(tmp.path(), &spec);
        let total: u64 = f.emitted.iter().map(|e| e.recorded_compressed_size).sum();
        assert_eq!(
            f.manifest.tail.ranges_at_least_1mib, 0,
            "fixture: tail empty"
        );
        assert!(
            f.emitted.iter().all(|e| e.recorded_compressed_size == SIZE),
            "fixture: every range is the uniform size"
        );

        let m = manager(tmp.path(), total);
        seed_total(&m, total).await;
        let need = bytes_to_free(total, total);
        assert!(need > SIZE, "fixture: the target must need several ranges");

        let freed = m.enforce_disk_cache_limits().await.unwrap();
        let (n, bytes) = evicted(tmp.path(), &f);

        assert!(
            freed >= need,
            "R13.3/R1.4 uniform extreme: the pass freed {freed} bytes against a target of \
             {need}. With the tail empty by construction, the full-population arm is the \
             only mechanism, and it fell short"
        );
        assert_eq!(
            bytes, freed,
            "the reported freed figure must be the bytes that left the disk"
        );
        assert_eq!(
            n as u64,
            need.div_ceil(SIZE),
            "R1.4: under uniform sizes the byte target implies an exact entry count; \
             {n} ranges were evicted for a target of {need} bytes at {SIZE} bytes each"
        );
    }

    /// One range holds most of the cache. The target exceeds every other range combined,
    /// so the pass can reach it only by evicting the dominant range. A selector that is
    /// blind to large ranges (a size cap, a fractional sample that misses it) frees every
    /// background range and still falls short.
    #[tokio::test(flavor = "multi_thread")]
    async fn single_dominant_extreme_evicts_the_dominant_range_to_reach_the_target() {
        const BACKGROUND: u64 = 4096;
        const DOMINANT: u64 = 4 * 1024 * 1024;
        let tmp = TempDir::new().unwrap();
        let spec = FixtureSpec {
            label: "dominant".to_string(),
            bucket: "fixture-dominant".to_string(),
            objects: 200,
            max_ranges_per_object: 1,
            distribution: SizeDistribution::SingleDominant {
                background: BACKGROUND,
                dominant: DOMINANT,
            },
            payload: PayloadMode::Genuine,
            ..FixtureSpec::default()
        };
        let f = generate(tmp.path(), &spec);
        let total: u64 = f.emitted.iter().map(|e| e.recorded_compressed_size).sum();
        let dominant: Vec<_> = f
            .emitted
            .iter()
            .filter(|e| e.recorded_compressed_size == DOMINANT)
            .collect();
        assert_eq!(dominant.len(), 1, "fixture: exactly one dominant range");
        let background_total = total - DOMINANT;

        let m = manager(tmp.path(), total);
        seed_total(&m, total).await;
        let need = bytes_to_free(total, total);
        assert!(
            need > background_total,
            "fixture: the target ({need}) must exceed all background bytes \
             ({background_total}), or the dominant range is not required"
        );

        let freed = m.enforce_disk_cache_limits().await.unwrap();
        let (_, bytes) = evicted(tmp.path(), &f);

        assert!(
            freed >= need,
            "R13.3 single-dominant extreme: the pass freed {freed} bytes against a target \
             of {need}; every background range together holds only {background_total}"
        );
        assert!(
            !tmp.path()
                .join("ranges")
                .join(&dominant[0].relative_bin_path)
                .exists(),
            "R13.3 single-dominant extreme: the dominant range must be evicted"
        );
        assert_eq!(
            bytes, freed,
            "the reported freed figure must be the bytes that left the disk"
        );
        assert!(
            freed < total,
            "the pass must not empty the cache to reach a 20% target"
        );
    }
}

/// R13.6: a shard's Tail_Partition written by one instance is what another instance's
/// selection reads.
///
/// Constructed per `cache-coherency-invariants.md` § "Constructing the test". Instance A's
/// contribution is a Tail_Partition file written directly, the way A's rolling rebuild
/// publishes it, without driving any local path on manager B. B is a fresh manager on the
/// same `cache_dir`: it has run no rolling pass, admitted nothing, and holds no tail-delta,
/// so nothing in B's own state names either key.
///
/// The fixture makes the two answers diverge. Two read-tier objects, P (2 MiB) and Q
/// (3 MiB), both above the 1 MiB floor and each large enough alone to cover the 1 MiB
/// target. A's partition names only P. Selection that reads the shared partition
/// (`select_eviction_candidates_bounded`, src/cache.rs) meets the target from P and evicts
/// P. Selection from local state alone has no partition, falls back to the full-population
/// collector, sorts size-descending and evicts Q. So the assertion that P went and Q stayed
/// can only pass if B consumed what A wrote.
mod r13_6_cross_instance {
    use super::*;

    const BACKDATE: Duration = Duration::from_secs(3600);

    /// Seed one unstaged single-range object. Returns `(bin_path, bucket, l1, leaf, at)`.
    fn seed(
        cache_dir: &Path,
        key: &str,
        size: u64,
    ) -> (PathBuf, String, String, String, SystemTime) {
        let at = SystemTime::now() - BACKDATE;
        let ranges_dir = cache_dir.join("ranges");
        let bin = get_sharded_path(&ranges_dir, key, &format!("_0-{}.bin", size - 1)).unwrap();
        let rel = bin
            .strip_prefix(&ranges_dir)
            .unwrap()
            .to_string_lossy()
            .to_string();
        std::fs::create_dir_all(bin.parent().unwrap()).unwrap();
        std::fs::write(&bin, vec![0u8; size as usize]).unwrap();
        let mut range = RangeSpec::new(0, size - 1, rel, CompressionAlgorithm::Lz4, size, size);
        range.created_at = at;
        range.last_accessed = at;
        range.staged = Some(false);
        let object_metadata = ObjectMetadata::new(
            "\"etag\"".to_string(),
            "Wed, 26 Aug 2026 00:00:00 GMT".to_string(),
            size,
            Some("application/octet-stream".to_string()),
        );
        let metadata = NewCacheMetadata {
            cache_key: key.to_string(),
            object_metadata,
            ranges: vec![range],
            created_at: at,
            expires_at: SystemTime::now() + Duration::from_secs(3600),
            compression_info: Default::default(),
            ..Default::default()
        };
        let meta_root = cache_dir.join("metadata");
        let meta = get_sharded_path(&meta_root, key, ".meta").unwrap();
        std::fs::create_dir_all(meta.parent().unwrap()).unwrap();
        std::fs::write(&meta, serde_json::to_string_pretty(&metadata).unwrap()).unwrap();
        let parts: Vec<String> = meta
            .strip_prefix(&meta_root)
            .unwrap()
            .components()
            .map(|c| c.as_os_str().to_string_lossy().to_string())
            .collect();
        (
            bin,
            parts[0].clone(),
            parts[1].clone(),
            parts[2].clone(),
            at,
        )
    }

    fn nanos(t: SystemTime) -> u64 {
        t.duration_since(UNIX_EPOCH).unwrap().as_nanos() as u64
    }

    #[tokio::test(flavor = "multi_thread")]
    async fn selection_follows_a_tail_partition_another_instance_wrote() {
        const P: u64 = 2 * 1024 * 1024;
        const Q: u64 = 3 * 1024 * 1024;
        let tmp = TempDir::new().unwrap();
        let (p_bin, bucket, l1, leaf, p_at) = seed(tmp.path(), "test-bucket/p-only-in-a.bin", P);
        let (q_bin, ..) = seed(tmp.path(), "test-bucket/q-local-scan.bin", Q);

        // Instance A's rebuild of P's shard, published as A publishes it:
        // `metadata/_shard_state/tails/{bucket}/{XX}.tail`, JSON lines, size-descending.
        let record = TailRecord {
            cache_key: "test-bucket/p-only-in-a.bin".to_string(),
            range_start: 0,
            range_end: P - 1,
            compressed_size: P,
            last_accessed: nanos(p_at),
            expires_at: 0,
            access_count: 1,
            is_staged: false,
            leaf,
        };
        let tail = tmp
            .path()
            .join("metadata/_shard_state/tails")
            .join(&bucket)
            .join(format!("{l1}.tail"));
        std::fs::create_dir_all(tail.parent().unwrap()).unwrap();
        std::fs::write(
            &tail,
            format!("{}\n", serde_json::to_string(&record).unwrap()),
        )
        .unwrap();

        // Manager B, on the same volume, constructed after A's write and never driven
        // through an admission, a rolling pass or a consolidation.
        let m = manager(tmp.path(), P + Q);
        seed_total(&m, P + Q).await;
        let need = bytes_to_free(P + Q, P + Q);
        const _: () = assert!(P < Q);
        assert!(
            need <= P,
            "fixture: each object alone covers the target ({need}) and the local fallback's \
             size-descending order prefers Q, so the two selection sources disagree"
        );
        assert!(
            std::fs::read_dir(tmp.path().join("metadata/_shard_state"))
                .unwrap()
                .flatten()
                .all(|e| !e.file_name().to_string_lossy().ends_with(".tail-delta")),
            "fixture: B must hold no tail-delta of its own"
        );

        let freed = m.enforce_disk_cache_limits().await.unwrap();

        assert!(
            !p_bin.exists() && q_bin.exists(),
            "R13.6: B's selection must follow the Tail_Partition A wrote (P evicted, Q kept). \
             Got p_exists={}, q_exists={}, freed={freed}. P gone with Q kept is reachable \
             only through the shared partition; Q gone means B selected from its own \
             full-population scan and ignored A's write",
            p_bin.exists(),
            q_bin.exists()
        );
        assert_eq!(freed, P, "the freed figure is P's recorded size");
    }
}
